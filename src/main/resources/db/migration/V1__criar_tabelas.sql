-- Famílias que confirmaram presença pelo formulário público.
-- A quantidade de pessoas NÃO é armazenada: é sempre calculada a partir de convidado.
CREATE TABLE familia (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome                VARCHAR(120) NOT NULL,
    chave_idempotencia  UUID,
    data_cadastro       TIMESTAMPTZ  NOT NULL DEFAULT now(),
    data_atualizacao    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT ck_familia_nome_nao_vazio CHECK (btrim(nome) <> ''),
    CONSTRAINT uk_familia_chave_idempotencia UNIQUE (chave_idempotencia)
);

CREATE INDEX idx_familia_data_cadastro ON familia (data_cadastro DESC);

CREATE TABLE convidado (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome_completo   VARCHAR(150) NOT NULL,
    familia_id      BIGINT       NOT NULL,
    data_cadastro   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT ck_convidado_nome_nao_vazio CHECK (btrim(nome_completo) <> ''),
    CONSTRAINT fk_convidado_familia FOREIGN KEY (familia_id)
        REFERENCES familia (id) ON DELETE CASCADE
);

CREATE INDEX idx_convidado_familia_id ON convidado (familia_id);

-- Administradores do painel. A senha é armazenada somente como hash BCrypt.
CREATE TABLE administrador (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario         VARCHAR(60)  NOT NULL,
    senha_hash      VARCHAR(100) NOT NULL,
    data_cadastro   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT uk_administrador_usuario UNIQUE (usuario)
);
